export type ReadingTip = {
  h: string;
  p: string;
  /** 手書き風の例（1要素＝1行） */
  memo?: string[];
  /** 比べる例（左＝避けたい書き方・右＝勧める書き方） */
  cmp?: [string, string];
  /** 記号の表（記号・意味） */
  legend?: [string, string][];
};
export type ReadingChapter = {
  id: string;
  c: string;
  /** 小口のインデックスに縦に並べる短い名前（1字ずつ改行する） */
  rail: string;
  h: string;
  tips: ReadingTip[];
};
export type Reading = {
  slug: string;
  href: string;
  /** ブラウザのタブに出る名前 */
  pageTitle: string;
  /** 題（ページの見出し・棚のカードの題・使い方ページの入口の題） */
  title: string;
  /** 棚のカードと使い方ページの入口に添える一言 */
  sub: string;
  /** 棚のカードの表紙（罫線の紙に手書き風の3行） */
  cover: string[];
  lead: string;
  chapters: ReadingChapter[];
};

