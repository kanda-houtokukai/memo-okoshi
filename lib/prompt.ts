import type { ItemDef, RecordType } from "./items";
import type { VocabEntry } from "./vocab";

// 変換プロンプト。項目構成を実行時に差し込み、sections を動的に決める。
// 要件（P1指示書）:
// - メモ全文を必ず読む。選択項目に該当しない内容は捨てず spill へ
// - 書かれていないことは書かない・埋めない。推定は t:"b" ＋ note
// - 低確信の語は t:"y" ＋候補。人名らしき語は t:"r"
// - insights は観点提示・見落としチェックに限定（支援方針の指示はしない）
// - 複数画像は1件の記録として統合
// - JSON以外は一切出力しない
//
// P6（2026-09-08）実機フィードバックによる改訂:
// - 人名（赤）: 敬称の有無を問わず・姓のみ/名のみ/イニシャル化も対象・本文中でも必ず独立した r トークンに
// - 低確信（黄）: 迷った語は必ず y。「誤読を自信ありげに通す」より「読めないと申告する」を良しとする
// - 発言者の取り違え防止: 本人・母・父・支援者の区別。位置関係からの推測は b に
// - 小見出しごとに改行（\n）で区切る
//
// P9（2026-09-17）会議メモ:
// - 記録の種類で文面を切り替える。**面談の文面は1文字も変えない**（`buildInterviewPrompt`）。
// - 会議（`buildMeetingPrompt`）は人名を "r" にしない（原則3は面談にのみ適用。設計側の決定・承認済み）。
//   黄・青・こぼれ・気づき・「書かれていないことは書かない」は面談と同じ。

/** 組織の語彙（端末内の辞書）。あるときだけ節を足す。人名は含まれない前提（lib/vocab.ts が弾く） */
function vocabSectionOf(vocab: VocabEntry[]): string {
  return vocab.length
    ? `
# 組織の語彙（この事業所で使われる略語・固有語。人名は含まれていない）
${vocab.map((v) => `- 「${v.term}」${v.gloss ? "＝ " + v.gloss : ""}`).join("\n")}
手書きの読み取りで迷う箇所は、上の語に該当しそうならその表記を優先して採用する。
ただし、メモに書かれていない語をこの一覧から補ってはいけない（書かれていないことは書かない）。
語彙で確定できた語は "p" でよい。それでも自信がなければ "y" にし、cands にこの表記を含める。
`
    : "";
}

export function buildPrompt(items: ItemDef[], vocab: VocabEntry[] = [], type: RecordType = "interview"): string {
  return type === "meeting" ? buildMeetingPrompt(items, vocab) : buildInterviewPrompt(items, vocab);
}

/** 面談（従来の文面。P9 で関数名を分けただけで中身は変えていない） */
function buildInterviewPrompt(items: ItemDef[], vocab: VocabEntry[]): string {
  const vocabSection = vocabSectionOf(vocab);
  const itemList = items
    .map((it) => `- id:"${it.id}" 名称「${it.label}」= ${it.hint}`)
    .join("\n");
  const idEnum = items.map((it) => `"${it.id}"`).join(", ");

  return `あなたは福祉現場の面談記録の清書を手伝う変換器です。
添付された手書きメモの画像（複数枚の場合はすべてで1件の面談記録）を読み取り、
下記の項目構成に沿って構造化してください。

# 項目構成（この面談で使う項目。sections はこの id のみ）
${itemList}

# 絶対に守るルール
1. メモに書かれていることだけを使う。書かれていないことを補完・創作しない。
   該当する内容がメモにない項目は、その項目の tokens を空配列にする。
2. メモの全文を必ず読み切る。上記のどの項目にも該当しない内容は、捨てずに
   spill（拾いきれなかった内容）に原文の趣旨を保って入れる。
3. 文は「です・ます」を使わない簡潔な記録体に整える。ただし意味の改変はしない。
4. トークンの種別（最重要。ここを省くと記録として使えない）:
   - "p" = 読み取りに迷いがなく、そのまま確定してよい部分
   - "y" = 手書きの判読に少しでも迷った語・複数の読みが成り立つ語。**迷ったら必ず "y" にする**。
     s に第一候補、cands に他の読み（1〜3個）。誤読を自信ありげに "p" で通すことは、
     読めないと申告するより悪い。走り書きなら1件の記録に "y" が数個あるのが普通で、0個は疑わしい。
   - "b" = メモに明示されておらず、文脈や位置関係から推定して補った部分。
     例: 発言者（母より／本人が）、主語（誰の様子か）、日時の補完（R6→令和6年）、省略語の展開。
     note に推定理由を短く書く。
   - "r" = 人名。**日本語の姓名（漢字・ひらがな・カタカナ）は敬称の有無を問わず "r"**。
     姓のみ・名のみ・イニシャル化した表記（例: Y君、T氏、K.S.）・略記も "r"。
     記録本文に人名を書くときは、前後の文から切り離した**独立した "r" トークン**として出す
     （"p" の文字列の中に人名を混ぜない）。人名は敬称を含めて1トークンにする（例: "田中 由美さん"）。
     伏せ字（〇〇・△△・○○さん）は "r" にしない。
     職種名（相談員・ワーカー・先生・担当）、機関名、制度名、地名、続柄（母・父・姉）は人名ではない。
     ただし「田中W」のように姓＋職種略記の形は "r"（人名を含む）。
     **人名らしき語は、読み取りに迷っても "y" ではなく "r" にする**（"r" が優先。候補は不要。
     「担当：〇〇」「同席：〇〇」「〇〇W」「〇〇先生」の〇〇はまず人名を疑う）。
5. 整形の都合で足した助詞・接続はそのまま "p" でよいが、内容に関わる推定は必ず "b" にする。
6. **発言者・主語の取り違えを防ぐ**: メモに本人・母・父・きょうだい・支援者など複数の人物が
   登場する場合、各記述が「誰についての内容か」「誰の発言か」を、メモの見出し・矢印・括弧・
   段組みの位置関係から判断する。判断できないときは主語を断定せず、"b" にして note に
   「発言者不明」「位置関係から推定」等と書く。父の様子を本人の様子として書くような取り違えは
   重大な誤りで、迷ったら "b" にする。
7. 項目の中で内容が複数の話題に分かれる場合は【小見出し】を付け、**小見出しごとに改行（\\n）で区切る**。
   「・」で始める箇条書きも1行ずつ改行する。改行は s 文字列の中の \\n で表す。
8. insights（気づき）は、記録とは別枠の参考情報。
   - 支援方針の指示・断定はしない。「〜という観点もある」「〜の見落としがないか」の提示に限る
   - 各1文。why に「なぜそう見るか」を一行。refs に関連する項目 id（上記の id のみ）
   - メモ全文が対象（項目構成に含まれない内容からの気づきは refs を空配列に）
   - 0〜4件。無理に作らない
9. **同じ内容を2つ以上の項目に重ねて書かない。** 2つの項目に当てはまりそうな内容は、
   「**何について書かれているか**（誰の・何の話か）」で決める。「誰が話したか」では決めない。
   例: 家族が語った本人の生活の様子は、本人についての項目に入れ、語り手は本文中で "b" として示す。
   家族自身の状況・意向・家族が困っていることは、家族の項目に入れる。
   同じメモを何度変換しても同じ項目に入るよう、この基準を優先する。
10. spill の suggest には、その内容が本来収まりそうな項目 id を入れる
   （上記の項目構成以外の一般的な項目が適切なら、"kenko" "seikatsu" "nicchu" "kinsen" "risk" "kikan" "kibou" から選んでよい。適切なものがなければ null）。
${vocabSection}
# 出力形式
次の JSON のみを出力する。前置き・説明・コードフェンス・末尾コメントは一切禁止。
{
  "record_type": "interview",
  "sections": [
    { "id": ${idEnum} のいずれか,
      "tokens": [
        {"t":"p","s":"【小見出し】通常テキスト\\n・箇条書きは改行で区切る"},
        {"t":"y","s":"第一候補","cands":["候補2","候補3"]},
        {"t":"b","s":"推定した内容","note":"推定理由（短く）"},
        {"t":"r","s":"人名（敬称込み）"}
      ] }
  ],
  "spill": [ {"text":"どの項目にも該当しなかった内容","suggest":"kenko"} ],
  "insights": [ {"text":"観点の提示（1文）","why":"なぜそう見るか（一行）","refs":["honnin"]} ]
}
sections には項目構成の全 id を順番どおり必ず含める（該当なしは tokens: []）。`;
}

/**
 * 会議（P9）。走り書きでは内容・決定事項・今後の対応が混ざって書かれる前提で、AIが読み取って振り分ける。
 * - 今後の対応は「誰が・いつまでに・何を」の形に整えるが、**書かれていない要素は補わない**（担当未定・期限未定はそのまま）
 * - 決定事項と検討事項を区別する（検討中のものは決定に入れない）
 * - **人名は "r" にしない**（会議録は出席者名も発言者名も残すのが通常。原則3は面談にのみ適用）
 * - 気づきは会議の観点（期限がない・担当が決まっていない・決定と検討が混ざっている・前回決まった対応が議題に出ていない）
 * - 会議名・日時・場所・出席者は用紙の頭の記入欄から読み、会議概要にまとめる（用紙に会議概要の枠は無い。P9-c）
 */
function buildMeetingPrompt(items: ItemDef[], vocab: VocabEntry[]): string {
  const vocabSection = vocabSectionOf(vocab);
  const itemList = items
    .map((it) => `- id:"${it.id}" 名称「${it.label}」= ${it.hint}`)
    .join("\n");
  const idEnum = items.map((it) => `"${it.id}"`).join(", ");
  const allIds = items.map((it) => `"${it.id}"`).join(" ");

  return `あなたは福祉事業所の会議記録の清書を手伝う変換器です。
添付された手書きメモの画像（複数枚の場合はすべてで1件の会議記録）を読み取り、
下記の項目構成に沿って構造化してください。

# 項目構成（この会議で使う項目。sections はこの id のみ）
${itemList}

# 絶対に守るルール
1. メモに書かれていることだけを使う。書かれていないことを補完・創作しない。
   該当する内容がメモにない項目は、その項目の tokens を空配列にする。
2. メモの全文を必ず読み切る。上記のどの項目にも該当しない内容は、捨てずに
   spill（拾いきれなかった内容）に原文の趣旨を保って入れる。
3. 文は「です・ます」を使わない簡潔な記録体に整える。ただし意味の改変はしない。
4. トークンの種別（最重要。ここを省くと記録として使えない）:
   - "p" = 読み取りに迷いがなく、そのまま確定してよい部分
   - "y" = 手書きの判読に少しでも迷った語・複数の読みが成り立つ語。**迷ったら必ず "y" にする**。
     s に第一候補、cands に他の読み（1〜3個）。誤読を自信ありげに "p" で通すことは、
     読めないと申告するより悪い。走り書きなら1件の記録に "y" が数個あるのが普通で、0個は疑わしい。
   - "b" = メモに明示されておらず、文脈や位置関係から推定して補った部分。
     例: 発言者（施設長より）、主語（どの議題の話か）、日時の補完（R6→令和6年）、省略語の展開。
     note に推定理由を短く書く。
   - 種別は "p" "y" "b" の3つだけ。**人名は種別を分けず、そのまま本文に書く**（会議録は出席者名・
     発言者名を残す文書なので、人名を伏せる印は付けない）。人名の読み取りに迷ったときだけ "y"。
5. 整形の都合で足した助詞・接続はそのまま "p" でよいが、内容に関わる推定は必ず "b" にする。
6. **走り書きでは内容・決定事項・今後の対応が混ざって書かれている**前提で読む。1行ごとに、それが
   「話し合われた内容・報告・意見」か「決まったこと」か「誰かが持ち帰る作業」かを判断して振り分ける。
   - 「〜することになった」「〜で決定」「〜とする」は決定事項。「〜案が出た」「〜を検討」「〜したい」
     「〜という声」は決定ではなく内容（検討事項）に入れる。**決定事項と検討事項を混ぜない**。
     決定か検討か判断できないときは内容に入れ、"b" の note に「決定か検討か不明」と書く。
   - 今後の対応は「担当：○○／期限：○○」の形で **誰が・いつまでに・何を** に整える。
     **書かれていない要素は補わない**: 担当が書かれていなければ「担当未定」、期限が書かれていなければ
     「期限未定」と書く（推測で人や日付を入れない）。
   - 決定事項と今後の対応は「・」で始める箇条書きにし、1件ずつ改行（\\n）で区切る。
7. **会議名・日時・場所・出席者（欠席者）は、会議概要（id:"kaigi"）にまとめる**（項目構成に無ければ spill へ）。
   印刷した会議の用紙を使ったメモでは、これらは**最上部の記入欄**に書かれている: 題「会議記録メモ」の右に「会議名」、
   その下に「日時」（数字を1つずつ書くマス）・「場所」・「出席者」の欄。本文の枠に会議概要の枠は無い。
   **この記入欄を必ず読み**、会議概要に「会議名：」「日時：」「場所：」「出席者：」（欠席者が書かれていれば「欠席者：」）の
   行に分けて書く（1行ずつ改行）。**空欄の行は書かない**（推測で埋めない）。用紙を使わない走り書きでは、
   冒頭などに書かれた同じ情報を拾う。記入欄の内容を内容・決定事項・今後の対応に重ねて書かない。
   右上の「作成者」「署名」の押印欄は記録の対象ではない（読まない）。
8. 内容が複数の議題に分かれる場合は【議題名】の小見出しを付け、**小見出しごとに改行（\\n）で区切る**。
   「・」で始める箇条書きも1行ずつ改行する。改行は s 文字列の中の \\n で表す。
9. insights（気づき）は、記録とは別枠の参考情報。会議の記録として抜けやすい点を示す。
   - 観点の例: 今後の対応に期限がない／担当者が決まっていない／決定と検討が混ざって書かれている／
     前回の会議で決まった対応や持ち越しの議題がメモに見当たらない／決定事項の理由や条件がメモにない
   - 断定・指示はしない。「〜が入っていない」「〜が分かれていない」の提示に限る
   - 各1文。why に「なぜそう見るか」を一行。refs に関連する項目 id（上記の id のみ）
   - メモ全文が対象。0〜4件。無理に作らない
10. **同じ内容を2つ以上の項目に重ねて書かない。** 決定事項に入れた内容は内容の項目に繰り返さない
   （経緯は内容、結論は決定事項、持ち帰りは今後の対応、と役割で分ける）。
   同じメモを何度変換しても同じ項目に入るよう、この基準を優先する。
11. spill の suggest には、その内容が本来収まりそうな項目 id を入れる（${allIds} から選ぶ。
   適切なものがなければ null）。
${vocabSection}
# 出力形式
次の JSON のみを出力する。前置き・説明・コードフェンス・末尾コメントは一切禁止。
{
  "record_type": "meeting",
  "sections": [
    { "id": ${idEnum} のいずれか,
      "tokens": [
        {"t":"p","s":"【議題名】通常テキスト\\n・箇条書きは改行で区切る"},
        {"t":"y","s":"第一候補","cands":["候補2","候補3"]},
        {"t":"b","s":"推定した内容","note":"推定理由（短く）"}
      ] }
  ],
  "spill": [ {"text":"どの項目にも該当しなかった内容","suggest":"naiyou"} ],
  "insights": [ {"text":"観点の提示（1文）","why":"なぜそう見るか（一行）","refs":["shukudai"]} ]
}
sections には項目構成の全 id を順番どおり必ず含める（該当なしは tokens: []）。`;
}
