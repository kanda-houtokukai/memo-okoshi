// [DECISION 2026-10-14 P25] 案は2つまで（設計側の指示）。P25 の評価の返答で見えた癖に合わせた:
//   - 3.5 Flash-Lite は、にじませた箇所を塗りつぶしと同じ「〇〇」で書いた（hard の眠剤・symbols の 10分・10/10）→ 案A
//   - 3.5 Flash・3.5 Flash-Lite は、読めない語を黙って省いた（names の「半分」）・大まかな語に言い換えた（眠剤→服薬・訪看→訪問）→ 案B
//   評価のメモ（eval/cases）に合わせた例は入れない（評価に合わせ込まないため）。

/** 足す位置の目印（本番のプロンプトの規則4の "y" の説明の最後の文） */
export const ANCHOR = '読めないと申告するより悪い。走り書きなら1件の記録に "y" が数個あるのが普通で、0個は疑わしい。';

export const VARIANTS: Record<string, { label: string; text: string }> = {
  A: {
    label: "にじみは塗りつぶしではない",
    text: `
     **字がにじんでいる・ぼやけている・かすれている箇所は「塗りつぶした箇所」ではない**。「〇〇」にせず、
     形から最も近い読みを s に書いて必ず "y" にする（cands に他の読み）。前後の文脈から読めた気がしても、
     字の形がはっきりしない箇所から作った語は "p" にしない（数字・日付・金額・回数・量・固有の名前はとくに）。`,
  },
  B: {
    label: "黙って省かない・言い換えない＋出す前の見直し",
    text: `
     **読めない語を黙って省かない。具体的な語を、より大まかな語に言い換えて済ませない**
     （省いたり言い換えたりすると、読めなかったことに誰も気づけない）。読めない語も "y" にして、形から最も近い読みを書く。
     JSON を出す前に、画像の中で字がにじんでいる・ぼやけている・かすれている箇所をすべて探し、
     その箇所に当たる語がすべて "y"（文脈から補ったなら "b"）になっているかを確かめてから出す。`,
  },
};

/** 本番のプロンプトに案を足す。目印が1か所でなければ止める（本番の文面が変わったら気づけるように） */
export function applyVariant(prompt: string, name: string): string {
  const v = VARIANTS[name];
  if (!v) throw new Error(`知らない案: ${name}（使えるのは ${Object.keys(VARIANTS).join(", ")}）`);
  const n = prompt.split(ANCHOR).length - 1;
  if (n !== 1) throw new Error(`案を足す位置の目印が ${n}か所ある（1か所のはず）`);
  return prompt.replace(ANCHOR, ANCHOR + v.text);
}
